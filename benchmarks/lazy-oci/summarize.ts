/**
 * run-1/SUMMARY.md — per-app tables plus the aggregate distributions the
 * decision actually rests on. Absolute differences are printed next to every
 * relative one, because a large percentage of a small number is not a product
 * (DESIGN.md, Outcome 4).
 *
 * Usage: bun benchmarks/lazy-oci/summarize.ts
 */
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { APPS } from './apps.ts';

const RUN = path.join(import.meta.dirname, 'run-1');
const ARMS = ['B0', 'B1', 'B2', 'B2d', 'B3a', 'B3b'] as const;

const readJson = <T>(p: string): T => JSON.parse(readFileSync(p, 'utf8')) as T;
const mb = (n: number) => (Number.isFinite(n) ? (n / 1e6).toFixed(1) : 'n/a');
const ms = (n: number) => (Number.isFinite(n) ? Math.round(n).toLocaleString() : 'n/a');
const pc = (n: number) => (Number.isFinite(n) ? `${(n * 100).toFixed(1)}%` : 'n/a');
const median = (xs: number[]) => {
  const s = xs.filter(Number.isFinite).sort((a, b) => a - b);
  if (!s.length) return Number.NaN;
  const m = s.length >> 1;
  return s.length % 2 ? s[m]! : (s[m - 1]! + s[m]!) / 2;
};

const apps = APPS.map((a) => a.name).filter((a) => existsSync(path.join(RUN, `${a}.metrics.json`)));
const M = new Map(apps.map((a) => [a, readJson<any>(path.join(RUN, `${a}.metrics.json`))]));

const L: string[] = [];
L.push('# Experiment 3 — semantic placement on a commodity lazy-OCI substrate\n');
L.push('Generated by `benchmarks/lazy-oci/summarize.ts`. Design and every metric formula were');
L.push('frozen in `DESIGN.md` before any arm ran.\n');

L.push('## Applications measured\n');
L.push('| app | criterion it was selected for | tree | SHA | universe files | universe MB | image blob MB |');
L.push('| --- | --- | --- | --- | ---: | ---: | ---: |');
for (const a of apps) {
  const m = M.get(a)!;
  L.push(
    `| ${a} | ${m.criterion} | ${m.tree} | \`${String(m.sha).slice(0, 10)}\` | ${m.universe.files.toLocaleString()} | ` +
      `${mb(m.universe.bytes)} | ${mb(m.images?.base?.blobBytes ?? Number.NaN)} |`,
  );
}

L.push('\n## Cold start — t0 (image asked for) to milestone, median over repetitions\n');
L.push('`first ok request` is the first held-out request that returned its expected status.');
L.push("For uptime-kuma the held-out workload OPENS with a socket.io command phase, so that");
L.push('column includes the phase duration: comparable across arms, not across apps.\n');
for (const a of apps) {
  const m = M.get(a)!;
  L.push(`\n### ${a}\n`);
  L.push('| arm | n | ready (ms) | first ok request (ms) | remote requests | remote MB | MB fetched by ready | prefetch files | prefetch MB | precision | recall | held-out misses (files / MB) | req p50 | req p95 |');
  L.push('| --- | ---: | ---: | ---: | ---: | ---: | ---: | ---: | ---: | ---: | ---: | ---: | ---: | ---: |');
  for (const arm of ARMS) {
    const x = m.byArm[arm];
    if (!x || !x.n) {
      L.push(`| ${arm} | 0 | — | — | — | — | — | — | — | — | — | — | — | — |`);
      continue;
    }
    L.push(
      `| ${arm} | ${x.n} | ${ms(x.tReadyMs.median)} | ${ms(x.tReq1Ms.median)} | ${ms(x.remoteRequests.median)} | ` +
        `${mb(x.remoteBytes.median)} | ${mb(x.bytesAtReady.median)} | ${x.prefetchedFiles?.toLocaleString() ?? '—'} | ` +
        `${mb(x.prefetchedFileBytes ?? Number.NaN)} | ` +
        `${pc(x.precision.median)} | ${pc(x.recall.median)} | ${ms(x.unexpectedMissFiles.median)} / ${mb(x.unexpectedMissBytes.median)} | ` +
        `${ms(x.latencyP50.median)} | ${ms(x.latencyP95.median)} |`,
    );
  }
  const bad = Object.entries(m.correctness ?? {}).filter(([, c]: any) => c.statusMismatch > 0);
  L.push(
    bad.length
      ? `\nCorrectness vs B0: **${bad.length} trial(s) diverged** — ${bad.map(([k, c]: any) => `${k}: ${c.statusMismatch}`).join(', ')}`
      : '\nCorrectness vs B0: every arm answered identically on every held-out request.',
  );
}

L.push('\n## The product question: B3b vs the strongest generic arm\n');
L.push('`generic` = the better of B2 and B2d per app and per metric — the null hypothesis at its strongest.\n');
L.push('| app | ready B0 | ready generic | ready B3b | Δ vs generic | remote req generic → B3b | held-out miss bytes generic → B3b |');
L.push('| --- | ---: | ---: | ---: | ---: | ---: | ---: |');
const deltas: { app: string; abs: number; rel: number; reqAbs: number }[] = [];
for (const a of apps) {
  const m = M.get(a)!;
  const g = (k: string, f: (v: any) => number) => {
    const c = [m.byArm.B2, m.byArm.B2d].filter((x) => x?.n);
    return c.length ? Math.min(...c.map(f)) : Number.NaN;
  };
  const genReady = g('ready', (x) => x.tReadyMs.median);
  const B3B = m.byArm.B3b?.n ? m.byArm.B3b : null;
  const b3b = B3B ? B3B.tReadyMs.median : Number.NaN;
  const genReq = g('req', (x) => x.remoteRequests.median);
  const genMiss = g('miss', (x) => x.unexpectedMissBytes.median);
  const abs = genReady - b3b;
  deltas.push({ app: a, abs, rel: abs / genReady, reqAbs: genReq - (B3B ? B3B.remoteRequests.median : Number.NaN) });
  L.push(
    `| ${a} | ${ms(m.byArm.B0?.n ? m.byArm.B0.tReadyMs.median : Number.NaN)} | ${ms(genReady)} | ${ms(b3b)} | ` +
      `${Number.isFinite(abs) ? `${abs > 0 ? '−' : '+'}${ms(Math.abs(abs))} ms (${pc(Math.abs(abs) / genReady)})` : 'n/a'} | ` +
      `${ms(genReq)} → ${ms(B3B ? B3B.remoteRequests.median : Number.NaN)} | ` +
      `${mb(genMiss)} → ${mb(B3B ? B3B.unexpectedMissBytes.median : Number.NaN)} |`,
  );
}
L.push(
  `\nMedian across apps: **${ms(median(deltas.map((d) => d.abs)))} ms** absolute ready-time advantage for B3b over the ` +
    `strongest generic arm (${pc(median(deltas.map((d) => d.rel)))} relative), ` +
    `${ms(median(deltas.map((d) => d.reqAbs)))} fewer remote requests.`,
);

L.push('\n## Does the arm just move the delay into the requests?\n');
L.push('A strategy is not a win if it reaches Ready sooner by deferring the same fetches into');
L.push('the first user requests. `B0` is the no-deferral reference: it starts with everything local.\n');
L.push('| app | p95 B0 | p95 B1 | p95 B2 | p95 B2d | p95 B3a | p95 B3b | worst-case deferral (generic) | (Reducer) |');
L.push('| --- | ---: | ---: | ---: | ---: | ---: | ---: | ---: | ---: |');
for (const a of apps) {
  const m = M.get(a)!;
  const p = (arm: string) => (m.byArm[arm]?.n ? m.byArm[arm].latencyP95.median : Number.NaN);
  const b0 = p('B0');
  const gen = Math.max(p('B2'), p('B2d'));
  const red = Math.max(p('B3a'), p('B3b'));
  L.push(
    `| ${a} | ${ms(b0)} | ${ms(p('B1'))} | ${ms(p('B2'))} | ${ms(p('B2d'))} | ${ms(p('B3a'))} | ${ms(p('B3b'))} | ` +
      `+${ms(gen - b0)} ms | +${ms(red - b0)} ms |`,
  );
}

L.push('\n## The many-small-files question: remote operations, not just bytes\n');
L.push('Public evidence says Node is hurt by the NUMBER of loose module files, not only by');
L.push('total size. If semantic clustering helps, it should show up as fewer remote operations');
L.push('for the same or fewer bytes.\n');
L.push('| app | arm | remote reqs | remote MB | remote ops / MB | ops per needed file |');
L.push('| --- | --- | ---: | ---: | ---: | ---: |');
for (const a of apps) {
  const m = M.get(a)!;
  for (const arm of ARMS) {
    const x = m.byArm[arm];
    if (!x?.n) continue;
    L.push(
      `| ${a} | ${arm} | ${ms(x.remoteRequests.median)} | ${mb(x.remoteBytes.median)} | ` +
        `${x.remoteOpsPerMB.median.toFixed(1)} | ${x.faultAmplification.median.toFixed(3)} |`,
    );
  }
}

L.push('\n## What lazy delivery is worth at all (vs the eager pull)\n');
L.push('`B1` is lazy with NO prefetch — the honest lower bound. `best lazy` is the fastest');
L.push('lazy arm for that app, i.e. what a tuned deployment would actually ship.\n');
L.push('| app | B0 ready | B1 ready | best lazy ready | B1 saving | best-lazy saving |');
L.push('| --- | ---: | ---: | ---: | ---: | ---: |');
const lazyGain: number[] = [];
for (const a of apps) {
  const m = M.get(a)!;
  const b0 = m.byArm.B0?.n ? m.byArm.B0.tReadyMs.median : Number.NaN;
  const b1 = m.byArm.B1?.n ? m.byArm.B1.tReadyMs.median : Number.NaN;
  const best = Math.min(
    ...['B1', 'B2', 'B2d', 'B3a', 'B3b'].map((k) => (m.byArm[k]?.n ? m.byArm[k].tReadyMs.median : Number.POSITIVE_INFINITY)),
  );
  lazyGain.push(b0 - best);
  L.push(
    `| ${a} | ${ms(b0)} | ${ms(b1)} | ${ms(best)} | ${ms(b0 - b1)} ms (${pc((b0 - b1) / b0)}) | ` +
      `${ms(b0 - best)} ms (${pc((b0 - best) / b0)}) |`,
  );
}
L.push(`\nMedian absolute cold-readiness saving from lazy delivery, best arm per app: **${ms(median(lazyGain))} ms**.`);

// ---- Experiment A
const expApps = apps.filter((a) => existsSync(path.join(RUN, `${a}.expA.json`)));
if (expApps.length) {
  L.push('\n## Experiment A — closed static trace vs recoverable complete artifact\n');
  L.push('| app | A1 (full) MB | A2 (closed NFT) MB | omitted | A2 TRAIN | A2 TEST | A3 TEST | held-out bytes outside the trace |');
  L.push('| --- | ---: | ---: | ---: | --- | --- | --- | ---: |');
  for (const a of expApps) {
    const e = readJson<any>(path.join(RUN, `${a}.expA.json`));
    const art = e.artifact;
    const st = (x: any) => (!x ? '—' : x.ready ? (x.statusMismatch ? `diverged (${x.statusMismatch})` : 'ok') : 'FAILED TO START');
    L.push(
      `| ${a} | ${mb(art.A1Bytes)} | ${mb(art.A2Bytes)} | ${pc(1 - art.A2Bytes / art.A1Bytes)} | ` +
        `${st(e.train?.A2)} | ${st(e.test?.A2)} | ${st(e.test?.A3)} | ` +
        `${e.neededOutsideTrace ? `${e.neededOutsideTrace.files} files / ${mb(e.neededOutsideTrace.bytes)} MB` : 'n/a'} |`,
    );
  }
}

writeFileSync(path.join(RUN, 'SUMMARY.md'), `${L.join('\n')}\n`);
console.log(L.join('\n'));
